#!/usr/bin/env python3
"""Embed the instruction list in a pre-built RP2040 firmware ELF.

The linker script (memory.x) allocates a fixed 96 KiB `.instrs` section filled with 0xFF.
This tool overwrites it inside the finished ELF, so the instructions can be swapped
without recompiling:

    python3 embed_instrs.py firmware.elf instrs.rle -o firmware-patched.elf
    probe-rs run --chip RP2040 firmware-patched.elf      # or elf2uf2-rs

Section layout (all little endian), which rp2040-impl/src/instr_store.rs reads back:

    offset  size  field
    0       4     magic  b"RLE1"
    4       4     payload length in bytes
    8       4     CRC-32 (zlib/IEEE) of the payload
    12      4     number of operations the payload decodes to
    16      ..    payload: the contents of instrs.rle
    ...           0xFF padding up to the end of the section (erased flash)
"""

import argparse
import struct
import sys
import zlib
from typing import NoReturn

SECTION = ".instrs"
MAGIC = b"RLE1"
HEADER = struct.Struct("<4sIII")
MAX_OPS = 76800  # 2n for the 320x120 canvas; same as the firmware's Vec capacity
MAX_OPCODE = 8  # Xp Xm Yp Ym D XpD XmD YpD YmD

SHT_NOBITS = 8
PT_LOAD = 1


def die(msg) -> NoReturn:
    sys.exit(f"error: {msg}")


def count_ops(payload):
    """Decode the RLE stream exactly as the firmware does and return the op count.

    Tokens are 10 bits, LSB first: 4 bit opcode, 6 bit (run length - 1). Leftover bits
    shorter than a token are padding."""

    ntokens = len(payload) * 8 // 10
    value = int.from_bytes(payload, "little")
    ops = 0
    for i in range(ntokens):
        token = (value >> (10 * i)) & 0x3FF
        opcode, run = token & 0xF, (token >> 4) + 1
        if opcode > MAX_OPCODE:
            die(f"token {i}: invalid opcode {opcode}")
        ops += run
    return ops


def read_elf_layout(elf):
    """Return (section file offset, size, vaddr) of .instrs after checking it is
    a loadable, file-backed section of a 32-bit little endian ARM ELF."""

    if elf[:4] != b"\x7fELF" or elf[4] != 1 or elf[5] != 1:
        die("not a 32-bit little endian ELF file")
    (
        _e_type,
        e_machine,
        _v,
        _entry,
        e_phoff,
        e_shoff,
        _flags,
        _ehsize,
        e_phentsize,
        e_phnum,
        e_shentsize,
        e_shnum,
        e_shstrndx,
    ) = struct.unpack_from("<HHIIIIIHHHHHH", elf, 16)
    if e_machine != 40:
        die(f"not an ARM ELF (e_machine={e_machine})")

    def shdr(i):
        return struct.unpack_from("<IIIIIIIIII", elf, e_shoff + i * e_shentsize)

    strtab = shdr(e_shstrndx)
    names = elf[strtab[4] : strtab[4] + strtab[5]]
    found = None
    for i in range(e_shnum):
        sh_name, sh_type, _fl, sh_addr, sh_off, sh_size, *_ = shdr(i)
        if names[sh_name : names.index(b"\0", sh_name)].decode() == SECTION:
            found = (sh_type, sh_addr, sh_off, sh_size)
    if not found:
        die(f"no {SECTION} section: was the firmware linked with the new memory.x?")
    sh_type, addr, off, size = found
    if sh_type == SHT_NOBITS:
        die(f"{SECTION} is NOBITS, it has no bytes in the file to patch")

    for i in range(e_phnum):
        p_type, p_off, p_vaddr, _pa, p_filesz, *_ = struct.unpack_from(
            "<IIIIIIII", elf, e_phoff + i * e_phentsize
        )
        if (
            p_type == PT_LOAD
            and p_off <= off
            and off + size <= p_off + p_filesz
            and p_vaddr + (off - p_off) == addr
        ):
            return off, size, addr
    die(f"{SECTION} is not inside a PT_LOAD segment, flashing tools would skip it")


def main():
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    ap.add_argument("elf", help="firmware ELF generated by cargo")
    ap.add_argument("rle", help="instrs.rle")
    ap.add_argument("-o", "--output", help="patched ELF (default: patch ELF in place)")
    args = ap.parse_args()

    with open(args.elf, "rb") as elf_file:
        elf_data = bytearray(elf_file.read())

    with open(args.rle, "rb") as instrs_file:
        instrs_data = instrs_file.read()

    if not instrs_data:
        die("instrs.rle is empty")

    off, size, addr = read_elf_layout(elf_data)
    capacity = size - HEADER.size

    if len(instrs_data) > capacity:
        die(f"{len(instrs_data)} bytes do not fit, the section holds {capacity}")

    ops = count_ops(instrs_data)

    if ops > MAX_OPS:
        die(f"{ops} operations exceed the limit of {MAX_OPS}")

    blob = (
        HEADER.pack(MAGIC, len(instrs_data), zlib.crc32(instrs_data), ops) + instrs_data
    )

    elf_data[off : off + size] = blob.ljust(size, b"\xff")

    out = args.output or args.elf

    with open(out, "wb") as patched_elf_file:
        patched_elf_file.write(elf_data)

    print(
        f"{out}: {ops} ops, {len(instrs_data)} bytes (crc {zlib.crc32(instrs_data):08x}) "
        f"at {addr:#010x}, {100 * len(blob) / size:.1f}% of {size // 1024} KiB"
    )


if __name__ == "__main__":
    main()
